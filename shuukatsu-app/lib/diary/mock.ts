import { DiaryAnalysisMode } from "./types";

/**
 * ダミーの日記分析結果（APIキーが無いとき・静的配信のとき用）。
 * 各スキルの出力フォーマットに合わせたサンプルを返す。
 */
export function mockDiaryAnalysis(mode: DiaryAnalysisMode): string {
  return mode === "gakuchika-seed" ? gakuchikaSample : interviewSample;
}

const noteFooter =
  "\n---\n\n※ これはサンプルの分析結果です（Claude APIキー未設定）。実際にはアップロードした日記の内容をもとに分析されます。";

const gakuchikaSample = `※ 以下は出力イメージのサンプルです。ES1文サンプルは「種」であり、そのまま提出用の完成文ではありません。

## 強みの種：対応力（Day12・4月20日）
> 日記の根拠：「バイトで急に一人で店を回すことになって、パニックになりかけたけどなんとか乗り切った」

- **状況（S）**：アルバイト先で、急遽一人で店舗を回すことになった。
- **課題（T）**：通常より少ない人数で、店舗の営業を成立させる必要があった。
- **行動（A）**：動揺しながらも、その場で対応して営業を乗り切った。
- **結果（R）**：（日記に成果の記載なし。本人に確認が必要）

**ES1文サンプル**：「私は予期しない状況でも投げ出さずに対応する力があります。アルバイトで急遽一人で店舗を任された経験を通じて発揮されました。」

## イチオシのガクチカ候補

〈対応力〉を推す。理由：状況・行動が日記から具体的に読み取れ、業界を問わず評価されやすい強みのため。

## さらに深めるための質問3つ

1. 一人で店を回したとき、具体的にどんな業務をどの順番でこなしましたか？
2. その日の売上やお客さんの数など、規模感が分かる数字はありますか？
3. 店長や同僚から、その日の対応について何か言われましたか？
${noteFooter}`;

const interviewSample = `※ 以下は出力イメージのサンプルです。質問への模範解答ではなく、本番前に自分の頭で考えるための予行演習ツールです。

## エピソード：一人で店を回した日（Day12・4月20日）
> 元の記述：「バイトで急に一人で店を回すことになって、パニックになりかけたけどなんとか乗り切った」

- **動機**：そのシフトを引き受けたとき、他に選択肢はありましたか？／断る・誰かを呼ぶという手もあった中でなぜ引き受けたのかを振り返ってみましょう。
- **判断**：一人で回す中で、何を優先して何を後回しにしましたか？／一番迷った瞬間と、その場の判断基準を思い出してみましょう。
- **困難**：「パニックになりかけた」のは具体的にどの場面でしたか？／大変さの中身（量・同時進行・初めての業務など）を具体化しておきましょう。
- **感情**：乗り切った直後、どんな気持ちでしたか？／安堵・達成感・悔しさなど、そのとき感じたことを場面とセットで思い出しましょう。
- **学び**：この経験はその後のバイトや他の場面で活きていますか？／同じ状況が来たら次はどうするかも考えておきましょう。

## 練習すべき質問トップ3

1. 「パニックになりかけたとき、最初に何をしましたか？」（一人で店を回したエピソード由来。困難への対応は面接官が最も深掘りしたがるポイントのため）
2. 「そのシフトを引き受けた理由を教えてください」（同エピソード由来。主体性と判断基準を確認したがるため）
3. 「その経験から学んだことを、入社後どう活かせますか？」（同エピソード由来。再現性を確認する定番の締め質問のため）
${noteFooter}`;
